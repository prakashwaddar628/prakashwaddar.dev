import type { CSSProperties } from "react";
import type { Config, Metrics } from "@/lib/system-lab/load-balancing";
import { ROUTING } from "@/lib/system-lab/load-balancing";

type Node = "client" | "balancer" | number;

export default function Architecture({ config, metrics, selected, onSelect, running }: {
  config: Config; metrics: Metrics | null; selected: Node; onSelect: (node: Node) => void; running: boolean;
}) {
  const flowing = running && !!metrics?.incoming;

  return (
    <div className="lab-graph" aria-label="Client to load balancer to application server architecture">
      <div className="lab-source">
        <button className="lab-node" type="button" aria-pressed={selected === "client"} onClick={() => onSelect("client")}
          title="Incoming traffic generated by the client">
          <span>01 / Source</span><strong>Client</strong><small>{config.incoming.toLocaleString("en-US")} req/s configured</small>
        </button>
        <div className={`lab-edge ${flowing ? "lab-flow" : ""}`} aria-hidden="true" />
        <button className="lab-node" type="button" aria-pressed={selected === "balancer"} onClick={() => onSelect("balancer")}
          title="Policy used to dispatch each incoming request">
          <span>02 / Router</span><strong>Load balancer</strong><small>{ROUTING[config.routing]}</small>
        </button>
      </div>
      <ul className="lab-fleet" aria-label="Application servers">
        {config.servers.map((server, index) => {
          const result = metrics?.servers.find(item => item.id === server.id);
          const share = metrics?.incoming ? (result?.admitted ?? 0) / metrics.incoming : 0;
          return (
            <li key={server.id}>
              <div className={`lab-edge ${flowing && server.online && share > 0 ? "lab-flow" : ""}`} data-offline={!server.online}
                style={{ "--packet-delay": `${index * -130}ms`, "--packet-speed": `${Math.round(1150 - share * 520)}ms` } as CSSProperties} aria-hidden="true" />
              <button className="lab-node lab-server" type="button" data-offline={!server.online}
                title={server.online ? "Inspect server capacity, queue, and latency" : "Inspect or restore this offline server"}
                aria-pressed={selected === server.id} onClick={() => onSelect(server.id)}>
                <span><i aria-hidden="true" />{server.online ? "Online" : "Offline"}</span>
                <strong>App {server.id}</strong>
                <small>{(result?.queued ?? 0).toLocaleString("en-US")} queued</small>
              </button>
            </li>
          );
        })}
      </ul>
    </div>
  );
}
